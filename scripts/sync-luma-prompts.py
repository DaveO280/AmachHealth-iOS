#!/usr/bin/env python3
"""Copy Luma's chat prompt config and its fixture from the website.

The website's src/lib/luma/__fixtures__/luma-prompt-cases.json holds the
prompt config served by GET /api/ai/prompts (as the exact JSON string) and
the messages /api/ai/chat builds for a set of inputs. This writes:

  AmachHealth/Sources/Services/Luma/LumaPromptConfig+Bundled.swift
      the bundled fallback config, and its hash (pinned for release builds)
  AmachHealth/Tests/Fixtures/LumaPromptCases.swift
      the fixture, for LumaPromptAssemblerTests

  python3 scripts/sync-luma-prompts.py ../Amach-Website/src/lib/luma/__fixtures__/luma-prompt-cases.json

Run it after every prompt change on the website (regenerate the fixture there
first: UPDATE_LUMA_PROMPT_FIXTURE=1 npx jest src/lib/luma).
"""
import hashlib
import json
import os
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..")


def raw_swift_string(text: str) -> str:
    """A Swift raw string literal that holds `text` exactly."""
    hashes = "#"
    # Neither the closing delimiter nor an interpolation (\#() may appear.
    while f'"{hashes}' in text or f"\\{hashes}" in text:
        hashes += "#"
    return f'{hashes}"""\n{text}\n"""{hashes}'


def main() -> None:
    with open(sys.argv[1], encoding="utf-8") as f:
        raw = f.read()
    fixture = json.loads(raw)
    config = fixture["config"]
    sha = hashlib.sha256(config.encode("utf-8")).hexdigest()
    assert sha == fixture["configSha256"], "fixture hash doesn't match its config"

    bundled = f"""// LumaPromptConfig+Bundled.swift
// AmachHealth
//
// GENERATED by scripts/sync-luma-prompts.py from the website's
// src/lib/luma/__fixtures__/luma-prompt-cases.json. Don't edit by hand.
//
// The prompt config GET /api/ai/prompts serves, bundled as the fallback for
// when the endpoint can't be reached, and its hash.

import Foundation

extension LumaPromptConfig {{
    /// SHA-256 of `bundledJSON`.
    static let bundledSHA256 = "{sha}"

    /// The exact JSON string the website serves as `config`.
    static let bundledJSON = {raw_swift_string(config)}
}}
"""
    cases = f"""// LumaPromptCases.swift
// AmachHealthTests
//
// GENERATED by scripts/sync-luma-prompts.py from the website's
// src/lib/luma/__fixtures__/luma-prompt-cases.json. Don't edit by hand.
//
// Inputs and the messages the website's /api/ai/chat builds for them.

enum LumaPromptCases {{
    static let json = {raw_swift_string(raw.rstrip(chr(10)))}
}}
"""
    for rel, text in [
        ("AmachHealth/Sources/Services/Luma/LumaPromptConfig+Bundled.swift", bundled),
        ("AmachHealth/Tests/Fixtures/LumaPromptCases.swift", cases),
    ]:
        with open(os.path.join(ROOT, rel), "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {rel}")
    print(f"config sha256 {sha}")


if __name__ == "__main__":
    main()
