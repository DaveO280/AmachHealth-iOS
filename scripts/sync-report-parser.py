#!/usr/bin/env python3
"""Copy the website's report parser bundle into the app.

The website builds its parser (src/utils/reportParsers) for JavaScriptCore:

  node scripts/build-device-parser.mjs        (in Amach-Website)

This writes AmachHealth/Sources/Services/ReportParsing/ReportParserBundle.swift
with the bundle as a string and its SHA-256, for DeviceReportParser. The app
never loads parser code from the network; a parser change ships with an app
release.

  python3 scripts/sync-report-parser.py ../Amach-Website/dist/device/report-parser.js
"""
import hashlib
import os
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..")
OUT = os.path.join(ROOT, "AmachHealth/Sources/Services/ReportParsing/ReportParserBundle.swift")


def raw_swift_string(text: str) -> str:
    """A Swift raw string literal that holds `text` exactly."""
    hashes = "#"
    # Neither the closing delimiter nor an interpolation (\\#() may appear.
    while f'"{hashes}' in text or f"\\{hashes}" in text:
        hashes += "#"
    return f'{hashes}"""\n{text}\n"""{hashes}'


def main() -> None:
    with open(sys.argv[1], encoding="utf-8") as f:
        source = f.read()
    # A multi-line raw string drops the newline after its opening and the one
    # before its closing delimiter, so this holds the file's text exactly.
    sha = hashlib.sha256(source.encode("utf-8")).hexdigest()
    sidecar = sys.argv[1] + ".sha256"
    if os.path.exists(sidecar):
        with open(sidecar, encoding="utf-8") as f:
            assert f.read().strip() == sha, "bundle doesn't match its .sha256"
    swift = f"""// ReportParserBundle.swift
// AmachHealth
//
// GENERATED by scripts/sync-report-parser.py from the website's
// dist/device/report-parser.js (scripts/build-device-parser.mjs). Don't edit
// by hand.
//
// The website's report parser, run by DeviceReportParser in JavaScriptCore.

import Foundation

enum ReportParserBundle {{
    /// SHA-256 of `source`.
    static let sha256 = "{sha}"

    static let source = {raw_swift_string(source)}
}}
"""
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(swift)
    print(f"{OUT}: {len(source)} chars, sha256={sha}")


if __name__ == "__main__":
    main()
