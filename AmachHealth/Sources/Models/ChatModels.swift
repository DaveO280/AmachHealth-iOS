// MARK: - Conversation Memory Types (iOS)
//
// Lightweight mirror of the web ConversationMemory structures, used to build
// the memory capsule that gets injected into AIChatContext on-device.

enum FactCategory: String, Codable {
    case medication
    case condition
    case goal
    case concern
    case preference
}

enum MemoryImportance: String, Codable {
    case critical
    case high
    case medium
    case low
}

struct CriticalFact: Codable, Identifiable {
    let id: UUID
    let category: FactCategory
    var value: String
    var context: String?
    let dateIdentified: Date
    var isActive: Bool
    /// When last confirmed. For a retired fact (isActive false), when it was retired.
    var lastConfirmed: Date?
    /// The timeline event the fact was drawn from, if any. Deleting or editing
    /// that event retires the fact: the timeline is the record of events.
    var sourceEventId: String? = nil

    var retiredAt: Date? { isActive ? nil : lastConfirmed }
}

/// One per chat session: its id is the session's id, and later extractions
/// from the same session replace it. Summaries from before that have their own ids.
struct SessionSummary: Codable, Identifiable {
    let id: UUID
    let date: Date
    let summary: String
    let topics: [String]
    let importance: MemoryImportance
    let messageCount: Int
    /// Timeline events the conversation discussed. Deleting or editing one
    /// drops the summary, as for facts drawn from it.
    var sourceEventIds: [String] = []
}

/// Storj-compatible payload for conversation memory sync.
/// Used for both local persistence and cross-platform sync via `dataType: "conversation-memory"`.
struct ConversationMemoryStorjPayload: Codable {
    var facts: [CriticalFact]
    var summaries: [SessionSummary]
}

@MainActor
final class ConversationMemoryStore: ObservableObject {
    static let shared = ConversationMemoryStore()

    @Published private(set) var facts: [CriticalFact] = []
    @Published private(set) var summaries: [SessionSummary] = []


    /// Memory lives in the vault (memory_facts / memory_summaries). Without
    /// a vault (no wallet) it is kept in memory for this run only.
    private var vault: VaultDatabase? { LocalVault.shared.database }

    private init() {}

    /// Reload from the vault after it opens or closes.
    func vaultDidChange() {
        extracted = []
        guard let vault else {
            facts = []
            summaries = []
            return
        }
        if let payload = try? vault.loadMemory() {
            facts = payload.facts
            summaries = payload.summaries
        }
        if let json = try? vault.meta(Self.extractedMetaKey),
           let stored = try? JSONDecoder().decode([ExtractionMark].self, from: Data(json.utf8)) {
            extracted = stored
        }
    }

    // MARK: - Extraction progress

    private static let extractedMetaKey = "memory_extracted"
    /// Sessions whose progress is kept; older entries are dropped.
    private static let extractedSessionsKept = 60

    private struct ExtractionMark: Codable {
        let session: UUID
        let messages: Int
    }

    /// How many messages of each session have been read for memory, most
    /// recently read last (vault_meta `memory_extracted`).
    private var extracted: [ExtractionMark] = []

    func extractedMessageCount(sessionId: UUID) -> Int {
        extracted.last { $0.session == sessionId }?.messages ?? 0
    }

    func markExtracted(sessionId: UUID, messageCount: Int) {
        extracted.removeAll { $0.session == sessionId }
        extracted.append(ExtractionMark(session: sessionId, messages: messageCount))
        extracted = Array(extracted.suffix(Self.extractedSessionsKept))
        guard let vault, let data = try? JSONEncoder().encode(extracted) else { return }
        try? vault.setMeta(Self.extractedMetaKey, String(decoding: data, as: UTF8.self))
    }

    func summary(forSession id: UUID) -> SessionSummary? {
        summaries.first { $0.id == id }
    }

    /// Active facts, oldest first, for the extractor to check against.
    func activeFactsForReview(limit: Int = 60) -> [CriticalFact] {
        Array(facts.filter(\.isActive).sorted { effectiveDate($0) < effectiveDate($1) }.suffix(limit))
    }

    // MARK: - Upsert with Value-Based Deduplication

    /// Retire facts the user said no longer hold, add or confirm new ones, and
    /// add or replace the summary (same id replaces).
    func upsert(facts newFacts: [CriticalFact], summary: SessionSummary?,
                retiring retiredIds: Set<UUID> = [], at date: Date = Date()) {
        for idx in facts.indices where facts[idx].isActive && retiredIds.contains(facts[idx].id) {
            facts[idx].isActive = false
            facts[idx].lastConfirmed = date
        }

        for newFact in newFacts {
            let newNorm = Self.normalizeFactValue(newFact.value)

            if let existingIdx = facts.firstIndex(where: {
                $0.category == newFact.category
                && $0.isActive
                && Self.factsOverlap(Self.normalizeFactValue($0.value), newNorm)
            }) {
                // Existing fact covers this — update in-place
                facts[existingIdx].lastConfirmed = Date()
                if newFact.value.count > facts[existingIdx].value.count {
                    facts[existingIdx].value = newFact.value
                }
                if let ctx = newFact.context, !ctx.isEmpty {
                    facts[existingIdx].context = ctx
                }
            } else {
                facts.append(newFact)
            }
        }

        if let summary {
            if let idx = summaries.firstIndex(where: { $0.id == summary.id }) {
                summaries[idx] = summary
            } else {
                summaries.append(summary)
            }
        }

        applyRetentionCaps()
        saveToDisk()
    }

    /// After a timeline event was deleted or edited: retire the facts drawn
    /// from it and drop the summaries of chats that discussed it, so memory
    /// keeps no copy of the event that can go stale. The timeline is the record.
    func forgetTimelineEvent(_ eventId: String, at date: Date = Date()) {
        let ids = Set(facts.filter { $0.isActive && $0.sourceEventId == eventId }.map(\.id))
        let summaryCount = summaries.count
        summaries.removeAll { $0.sourceEventIds.contains(eventId) }
        guard !ids.isEmpty || summaries.count != summaryCount else { return }
        upsert(facts: [], summary: nil, retiring: ids, at: date)
    }

    // Storj sync removed in Phase 3: memory lives in the vault and in the encrypted backup.

    // MARK: - Memory Capsule Builder

    private static func intentRelevantCategories(_ intent: ChatIntent) -> Set<FactCategory> {
        switch intent {
        case .sleep, .recovery: return [.goal, .concern, .condition]
        case .activity: return [.goal, .condition]
        case .vitals: return [.condition, .concern]
        case .labs: return [.condition, .medication, .concern]
        case .medications: return [.medication, .condition, .preference]
        case .bodyComp: return [.goal, .condition]
        case .general: return []
        }
    }

    /// Build memory capsule. Quick mode + intent: only facts in intent-relevant categories (capped). Deep: full capsule.
    func buildMemoryCapsule(intent: ChatIntent? = nil, mode: ChatMode = .quick) -> AIChatMemoryCapsule? {
        let activeFacts = facts.filter { $0.isActive }
        guard !activeFacts.isEmpty || !summaries.isEmpty else { return nil }

        let filteredFacts: [CriticalFact]
        if mode == .deep || intent == nil {
            filteredFacts = activeFacts
        } else {
            let relevanceCategories = Self.intentRelevantCategories(intent!)
            // Preferences shape every answer, whatever the topic.
            var list = activeFacts.filter {
                relevanceCategories.isEmpty || relevanceCategories.contains($0.category) || $0.category == .preference
            }
            if list.count > 15 { list = Array(list.suffix(15)) }
            filteredFacts = list
        }

        func truncated(_ text: String, maxLen: Int) -> String {
            let collapsed = text.replacingOccurrences(
                of: "\\s+",
                with: " ",
                options: .regularExpression
            ).trimmingCharacters(in: .whitespacesAndNewlines)
            if collapsed.count <= maxLen { return collapsed }
            let idx = collapsed.index(collapsed.startIndex, offsetBy: maxLen)
            return String(collapsed[..<idx]).trimmingCharacters(in: .whitespacesAndNewlines) + "…"
        }

        func latestValues(for category: FactCategory, limit: Int?) -> [String] {
            let sorted = filteredFacts.filter { $0.category == category }
                .sorted { effectiveDate($0) < effectiveDate($1) }
            let sliced = limit != nil ? Array(sorted.suffix(limit!)) : sorted
            // Month noted, so Luma can tell a fact from last week from one a year old.
            return sliced.map { "\(truncated($0.value, maxLen: 120)) (noted \(Self.monthYear(effectiveDate($0))))" }
        }

        let activeGoals = latestValues(for: .goal, limit: 6)
        let activeConcerns = latestValues(for: .concern, limit: 6)
        let medications = latestValues(for: .medication, limit: 20)
        let conditions = latestValues(for: .condition, limit: 20)
        let preferences = latestValues(for: .preference, limit: 8)

        let recentSummaries = Self.pickSummaries(summaries, intent: intent, mode: mode)
            .map { "\(LumaDate.day($0.date)) (\(LumaDate.age(of: $0.date))): \(truncated($0.summary, maxLen: 150))" }

        if activeGoals.isEmpty,
           activeConcerns.isEmpty,
           medications.isEmpty,
           conditions.isEmpty,
           preferences.isEmpty,
           recentSummaries.isEmpty {
            return nil
        }

        return AIChatMemoryCapsule(
            activeGoals: activeGoals,
            activeConcerns: activeConcerns,
            medications: medications,
            conditions: conditions,
            preferences: preferences,
            recentSessionNotes: recentSummaries
        )
    }

    /// Most recent session summaries, plus older ones on the question's topic,
    /// oldest first and within `summaryCharBudget`.
    static let summaryCharBudget = 1_000

    nonisolated static func pickSummaries(_ all: [SessionSummary], intent: ChatIntent?, mode: ChatMode) -> [SessionSummary] {
        let sorted = all.sorted { $0.date < $1.date }
        let recentCount = mode == .deep ? 6 : 3
        var picked = Array(sorted.suffix(recentCount))
        if let intent, intent != .general {
            let onTopic = sorted.dropLast(recentCount).filter {
                ChatIntentClassifier.classifyAll(($0.topics + [$0.summary]).joined(separator: ". ")).contains(intent)
            }
            picked = Array(onTopic.suffix(2)) + picked
        }
        // Drop from the oldest until the notes fit (each is shown at up to ~150 characters plus a date).
        while picked.count > 1, picked.reduce(0, { $0 + min($1.summary.count, 150) + 30 }) > summaryCharBudget {
            picked.removeFirst()
        }
        return picked
    }

    private static func monthYear(_ date: Date) -> String {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "MMM yyyy"
        return f.string(from: date)
    }

    // MARK: - Dedup Helpers

    nonisolated static func normalizeFactValue(_ value: String) -> String {
        value.lowercased()
            .replacingOccurrences(of: "\\s+", with: " ", options: .regularExpression)
            .trimmingCharacters(in: .whitespacesAndNewlines)
    }

    /// Two normalized values overlap if one equals or is a substring of the other.
    private static func factsOverlap(_ a: String, _ b: String) -> Bool {
        a == b || a.contains(b) || b.contains(a)
    }

    /// Effective recency: lastConfirmed if set, otherwise dateIdentified.
    private func effectiveDate(_ fact: CriticalFact) -> Date {
        fact.lastConfirmed ?? fact.dateIdentified
    }

    // MARK: - Merge (Storj pull)

    private func mergeRemoteMemory(_ remote: ConversationMemoryStorjPayload) {
        let merged = Self.merge(
            local: ConversationMemoryStorjPayload(facts: facts, summaries: summaries),
            remote: remote
        )
        facts = merged.facts
        summaries = merged.summaries
        saveToDisk()
    }

    /// Merge facts (dedup by category + normalized value, newer wins) and
    /// summaries (union by id), then apply the retention caps.
    nonisolated static func merge(
        local: ConversationMemoryStorjPayload,
        remote: ConversationMemoryStorjPayload
    ) -> ConversationMemoryStorjPayload {
        var localByKey: [String: CriticalFact] = [:]
        for fact in local.facts { localByKey[factMergeKey(fact)] = fact }

        for remoteFact in remote.facts {
            let key = factMergeKey(remoteFact)
            if let existing = localByKey[key] {
                let existingDate = existing.lastConfirmed ?? existing.dateIdentified
                let remoteDate = remoteFact.lastConfirmed ?? remoteFact.dateIdentified
                if remoteDate > existingDate {
                    localByKey[key] = remoteFact
                }
            } else {
                localByKey[key] = remoteFact
            }
        }

        var summariesById: [UUID: SessionSummary] = [:]
        for summary in local.summaries { summariesById[summary.id] = summary }
        // A session's summary is updated as it grows: keep the newer.
        for remoteSummary in remote.summaries
        where summariesById[remoteSummary.id].map({ remoteSummary.date > $0.date }) ?? true {
            summariesById[remoteSummary.id] = remoteSummary
        }

        var merged = ConversationMemoryStorjPayload(
            facts: Array(localByKey.values),
            summaries: Array(summariesById.values)
        )
        applyRetentionCaps(&merged)
        return merged
    }

    #if DEBUG
    /// DEBUG: Apply a replay payload with original dates (replace all, or merge like a Storj pull).
    func debugApplyReplayMemory(_ payload: ConversationMemoryStorjPayload, mergeIntoExisting: Bool) {
        if mergeIntoExisting {
            mergeRemoteMemory(payload)
        } else {
            facts = payload.facts
            summaries = payload.summaries
            applyRetentionCaps()
            saveToDisk()
        }
    }
    #endif

    nonisolated private static func factMergeKey(_ fact: CriticalFact) -> String {
        "\(fact.category.rawValue):\(normalizeFactValue(fact.value))"
    }

    // MARK: - Persistence

    private func applyRetentionCaps() {
        var payload = ConversationMemoryStorjPayload(facts: facts, summaries: summaries)
        Self.applyRetentionCaps(&payload)
        facts = payload.facts
        summaries = payload.summaries
    }

    nonisolated private static func applyRetentionCaps(_ payload: inout ConversationMemoryStorjPayload) {
        payload.facts.sort { $0.dateIdentified < $1.dateIdentified }
        if payload.facts.count > 200 {
            payload.facts = Array(payload.facts.suffix(200))
        }

        payload.summaries.sort { $0.date < $1.date }
        if payload.summaries.count > 40 {
            payload.summaries = Array(payload.summaries.suffix(40))
        }
    }

    private func saveToDisk() {
        guard let vault else { return }
        do {
            try vault.replaceMemory(facts: facts, summaries: summaries)
        } catch {
            #if DEBUG
            print("⚠️ ConversationMemoryStore: vault write failed: \(error.localizedDescription)")
            #endif
        }
    }
}

